package commands

import (
	"fmt"
	"io"
	"os"
	"strings"
)

const handoffPath = "HANDOFF.md"

func handleWrap(_ string, w io.Writer) (bool, error) {
	branch := gitCurrentBranch()
	if branch == "" {
		fmt.Fprintln(w, "error: not in a git repository")
		return true, nil
	}

	logR := runCmd("git", "log", "--oneline", "-10")
	diffR := runCmd("git", "diff", "--stat", "HEAD")
	statusR := runCmd("git", "status", "--short")

	status := strings.TrimSpace(statusR.Stdout)
	if status == "" {
		status = "(clean)"
	}

	var sb strings.Builder
	fmt.Fprintf(&sb, "## Overview\n\n")
	fmt.Fprintf(&sb, "Handoff snapshot generated by `wi /wrap`. Captures branch state, recent commits, "+
		"working-tree status, and space for the context a next session needs. Fill in the templated "+
		"sections before closing out.\n\n---\n\n")
	fmt.Fprintf(&sb, "## Branch\n\n`%s`\n\n", branch)
	fmt.Fprintf(&sb, "## Recent Commits\n\n```\n%s\n```\n\n", strings.TrimSpace(logR.Stdout))
	fmt.Fprintf(&sb, "## Diff Stat\n\n```\n%s\n```\n\n", strings.TrimSpace(diffR.Stdout))
	fmt.Fprintf(&sb, "## Working Tree\n\n```\n%s\n```\n\n", status)
	fmt.Fprintf(&sb, "## Key Decisions\n\n_Fill in: architecture decisions or constraints made this session._\n\n")
	fmt.Fprintf(&sb, "## Next Steps\n\n_Fill in: what should the next session pick up first._\n\n")
	fmt.Fprintf(&sb, "## Blockers\n\n_Fill in: anything stalled or waiting on external input._\n")

	if err := os.WriteFile(handoffPath, []byte(sb.String()), 0o644); err != nil {
		return true, fmt.Errorf("wrap: write HANDOFF.md: %w", err)
	}
	fmt.Fprintln(w, "wrote HANDOFF.md")
	return true, nil
}
